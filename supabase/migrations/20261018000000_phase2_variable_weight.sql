-- ============================================================
-- market-price / Phase 2: 量り売りの商品に印を付ける
--
-- 困っていたこと:
--   精肉・鮮魚・青果の量り売りは、同じ商品でもパックごとにグラム数が違う。
--   「298円のひき肉」と「412円のひき肉」を値段そのままで比べても意味が無く、
--   100g あたりに直して初めて比べられる。
--   一方で卵・牛乳・加工食品は規格品なので、そのままの値段で比べてよい。
--
--   これまでは画面の「100gあたりで比べる」を毎回手で入れ替える必要があった。
--   商品そのものの性質なので、商品側に覚えさせる。
--
-- category も一緒に埋めるようにする。
--   これまで列はあったが一度も使われておらず、検索も素通りしていた。
--
-- ★ 冪等(何度実行しても同じ結果)・非破壊:
--   DROP TABLE / TRUNCATE / DELETE は 1 つも含まれていません。
--   既存の行には既定値 false が入るだけで、記録は一切変わりません。
-- ============================================================

-- ------------------------------------------------------------
-- 1. 量り売りかどうかの印
--
--    true = パックごとにグラム数が変わる(精肉・鮮魚・青果の量り売りなど)
--    この印が付いた商品は、
--      - 高い/安いの判定を既定で「100g あたり」で行う
--      - 記録するとき、そのパックの実際のグラム数を毎回入れてもらう
--    後者が無いと、登録時のグラム数で計算してしまい単価が狂う。
-- ------------------------------------------------------------
alter table public.products
  add column if not exists is_variable_weight boolean not null default false;

comment on column public.products.is_variable_weight is
  'パックごとにグラム数が変わる商品(量り売りの精肉・鮮魚など)。'
  'true なら単価(100gあたり)で比べ、記録時に実際のグラム数を入れてもらう。';

comment on column public.products.category is
  '分類(例: 精肉、鮮魚、乳製品)。検索と、量り売りかどうかの判断の手がかりに使う。';

-- 量り売りの商品を一覧の中から引けるようにする(件数は多くないが素直に)
create index if not exists products_user_variable_weight_idx
  on public.products (user_id, is_variable_weight)
  where is_variable_weight;
